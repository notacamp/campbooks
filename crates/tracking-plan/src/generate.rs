//! What the plan generates: the canonical mirror
//! (`tracking/tracking-plan.json`, a JSON Schema per event) and one
//! `tracking.gen.rs` per owning crate. Both are byte-stable: sorted keys,
//! rows in canonical order, a trailing newline.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use serde_json::{Value, json};

use crate::check::crate_of;
use crate::model::{
    EventRow, Plan, enum_type_name, event_type_name, module_of, pascal, record_type_name,
};

/// The header of every generated Rust file.
pub const RUST_HEADER: &str = "// @generated by campbooks-tracking-plan — do not edit.";

/// Where the mirror is written, relative to the repository root.
pub const MIRROR: &str = "tracking/tracking-plan.json";

/// Where an owning crate's generated code goes, relative to the repository
/// root.
pub fn rust_path(owner: &str) -> String {
    if owner == "kernel" {
        "crates/kernel/src/tracking/tracking.gen.rs".to_owned()
    } else {
        format!("crates/modules/{owner}/src/tracking.gen.rs")
    }
}

/// Every generated file: path (relative to the repository root) → content.
pub fn files(plan: &Plan) -> BTreeMap<String, String> {
    let mut plan = plan.clone();
    plan.sort();
    let mut files = BTreeMap::new();
    files.insert(MIRROR.to_owned(), mirror(&plan));
    let mut owners: BTreeSet<&str> = BTreeSet::from(["kernel"]);
    owners.extend(plan.events.iter().map(|e| crate_of(&e.module)));
    owners.extend(plan.records.iter().map(|r| crate_of(module_of(&r.record))));
    owners.extend(
        plan.enums
            .iter()
            .map(|e| crate_of(module_of(&e.enumeration))),
    );
    for owner in owners {
        files.insert(rust_path(owner), rust(&plan, owner));
    }
    files
}

// --- the mirror ---------------------------------------------------------------

/// The canonical JSON mirror of the plan.
pub fn mirror(plan: &Plan) -> String {
    let events: Vec<Value> = plan
        .events
        .iter()
        .map(|event| {
            let mut value = serde_json::to_value(event).unwrap_or(Value::Null);
            if let Value::Object(map) = &mut value {
                map.insert("rust_type".to_owned(), json!(event_type_name(event)));
                map.insert("schema".to_owned(), event_schema(plan, event));
            }
            value
        })
        .collect();
    let document = json!({
        "description": "The tracking plan (ADR 0020), generated from tracking/tracking-plan.xlsx \
            by campbooks-tracking-plan. Do not edit: change the workbook and regenerate. Every \
            event's `schema` is the JSON Schema of its body; `envelope` is the schema of what \
            the kernel adds around it.",
        "generated_by": "campbooks-tracking-plan",
        "plan_version": plan.version(),
        "plan_date": plan.date(),
        "envelope": envelope_schema(),
        "events": events,
        "properties": plan.properties,
        "records": plan.records,
        "enums": plan.enums,
        "actors": plan.actors,
        "coverage": plan.coverage,
        "changelog": plan.changelog,
    });
    let mut text = serde_json::to_string_pretty(&document).unwrap_or_default();
    text.push('\n');
    text
}

/// The JSON Schema of the envelope the kernel writes around every body.
fn envelope_schema() -> Value {
    let actor = json!({
        "type": "object",
        "additionalProperties": false,
        "required": ["type"],
        "properties": {
            "type": {"enum": crate::model::ACTOR_TYPES},
            "id": {"type": "string", "description": "See the Actors sheet: an account id, a \
                client id Campbooks minted (none for any other client), a job kind or a \
                command's name; never a name, an address or a URL."},
        },
    });
    json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "Tracked event envelope",
        "type": "object",
        "additionalProperties": false,
        "required": ["id", "name", "version", "occurred_at", "actor", "correlation", "role",
            "app_version", "plan_version"],
        "properties": {
            "id": {"type": "string", "format": "uuid", "description": "The event's id \
                (UUIDv7); subscribers deduplicate on it."},
            "name": {"type": "string"},
            "version": {"type": "integer", "minimum": 1},
            "occurred_at": {"type": "string", "format": "date-time"},
            "workspace_id": {"type": ["string", "null"], "format": "uuid"},
            "actor": actor,
            "on_behalf_of": {"anyOf": [actor, {"type": "null"}]},
            "operation": {"type": ["string", "null"], "description": "The operationId being \
                served, when inside an operation."},
            "correlation": {"type": "string", "description": "The request's trace id, carried \
                into every job and delivery it causes."},
            "causation": {
                "anyOf": [
                    {
                        "type": "object",
                        "additionalProperties": false,
                        "required": ["type", "id"],
                        "properties": {
                            "type": {"enum": ["job", "event"]},
                            "id": {"type": "string", "format": "uuid"},
                        },
                    },
                    {"type": "null"},
                ],
            },
            "role": {"enum": ["all", "api", "worker", "cli"]},
            "app_version": {"type": "string"},
            "plan_version": {"type": "integer", "minimum": 1},
        },
    })
}

/// The JSON Schema of one event version's body.
pub fn event_schema(plan: &Plan, event: &EventRow) -> Value {
    let mut properties = serde_json::Map::new();
    let mut required = Vec::new();
    for row in plan.properties_of(&event.name, event.version) {
        let mut schema = type_schema(plan, &row.kind, &row.of, &row.pattern);
        if row.list {
            schema = json!({"type": "array", "items": schema});
        }
        if let Value::Object(map) = &mut schema {
            map.insert("description".to_owned(), json!(row.description));
            if !row.example.is_empty() {
                map.insert("examples".to_owned(), json!([row.example]));
            }
            map.insert("x-classification".to_owned(), json!(row.classification));
        }
        properties.insert(row.property.clone(), schema);
        if row.required {
            required.push(row.property.clone());
        }
    }
    json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": format!("urn:campbooks:tracking:{}:v{}", event.name, event.version),
        "title": event.name,
        "description": event.description,
        "type": "object",
        "additionalProperties": false,
        "required": required,
        "properties": properties,
    })
}

fn type_schema(plan: &Plan, kind: &str, of: &str, pattern: &str) -> Value {
    match kind {
        "id" => json!({"type": "string", "format": "uuid"}),
        "record_ref" => json!({
            "type": "object",
            "additionalProperties": false,
            "required": ["type", "id"],
            "properties": {
                "type": {"type": "string", "pattern": "^[a-z][a-z0-9_]*\\.[a-z][a-z0-9_]*$"},
                "id": {"type": "string"},
            },
        }),
        "record" => record_schema(plan, of),
        "enum" => {
            let values: Vec<&str> = plan.values_of(of).map(|row| row.value.as_str()).collect();
            json!({"type": "string", "enum": values})
        }
        "bool" => json!({"type": "boolean"}),
        "int" => json!({"type": "integer"}),
        "decimal" => json!({"type": "string", "pattern": "^-?[0-9]+(\\.[0-9]+)?$"}),
        "duration_ms" | "bytes" => json!({"type": "integer", "minimum": 0}),
        "timestamp" => json!({"type": "string", "format": "date-time"}),
        "date" => json!({"type": "string", "format": "date"}),
        "currency" => json!({"type": "string", "pattern": "^[A-Z]{3}$"}),
        "country" => json!({"type": "string", "pattern": "^[A-Z]{2}$"}),
        "locale" => json!({"type": "string", "pattern": "^[a-z]{2,3}(-[A-Z]{2})?$"}),
        _ => json!({"type": "string", "pattern": pattern}),
    }
}

fn record_schema(plan: &Plan, record: &str) -> Value {
    let mut properties = serde_json::Map::new();
    let mut required = Vec::new();
    for row in plan.fields_of(record) {
        let mut schema = type_schema(plan, &row.kind, &row.enumeration, &row.pattern);
        if row.list {
            schema = json!({"type": "array", "items": schema});
        }
        if let Value::Object(map) = &mut schema {
            map.insert("description".to_owned(), json!(row.description));
            map.insert("x-classification".to_owned(), json!(row.classification));
        }
        properties.insert(row.field.clone(), schema);
        if row.required {
            required.push(row.field.clone());
        }
    }
    json!({
        "title": record,
        "type": "object",
        "additionalProperties": false,
        "required": required,
        "properties": properties,
    })
}

// --- Rust ---------------------------------------------------------------------

/// Longest line rustfmt keeps as it is (`rustfmt.toml`'s `max_width`).
const MAX_WIDTH: usize = 100;

/// The generated Rust of owning crate `owner`: rustfmt-clean by
/// construction, so `cargo fmt --check` passes on it unchanged.
pub fn rust(plan: &Plan, owner: &str) -> String {
    let types = if owner == "kernel" {
        "crate::tracking::types"
    } else {
        "campbooks_kernel::tracking::types"
    };
    let mut items: Vec<String> = Vec::new();
    if owner == "kernel" {
        items.push(format!(
            "/// The tracking plan version this build was generated from (the newest row of its\n\
             /// Changelog), written into every event's envelope.\n\
             pub const PLAN_VERSION: u32 = {};",
            plan.version()
        ));
        items.push(format!(
            "/// The date of [`PLAN_VERSION`].\npub const PLAN_DATE: &str = \"{}\";",
            plan.date()
        ));
    }
    let enums: BTreeSet<&str> = plan
        .enums
        .iter()
        .map(|row| row.enumeration.as_str())
        .filter(|name| crate_of(module_of(name)) == owner)
        .collect();
    let records: BTreeSet<&str> = plan
        .records
        .iter()
        .map(|row| row.record.as_str())
        .filter(|name| crate_of(module_of(name)) == owner)
        .collect();
    for event in plan
        .events
        .iter()
        .filter(|event| crate_of(&event.module) == owner)
    {
        items.push(event_struct(plan, event));
        items.push(event_impl(event));
    }
    for record in records {
        items.push(record_struct(plan, record));
    }
    for enumeration in enums {
        items.push(enum_item(plan, enumeration));
    }

    let body = items.join("\n\n");
    let mut out = String::new();
    out.push_str(RUST_HEADER);
    out.push_str("\n//\n");
    let _ = writeln!(
        out,
        "// The tracked events {}, from the tracking plan",
        if owner == "kernel" {
            "of the kernel and the server".to_owned()
        } else {
            format!("of `{owner}`")
        }
    );
    let _ = writeln!(
        out,
        "// (`tracking/tracking-plan.xlsx`, version {}). Change the plan, then run",
        plan.version()
    );
    out.push_str(
        "// `cargo run -p campbooks-tracking-plan -- generate` (ADR 0020, docs/tracking.md).\n\n",
    );
    out.push_str("#![allow(clippy::pedantic)]\n\n");
    if body.contains("types::") {
        let _ = writeln!(out, "use {types};\n");
    }
    out.push_str(&body);
    out.push('\n');
    out
}

/// `///` lines for `text` (one per line of it), indented by `indent`.
fn doc(text: &str, indent: &str) -> String {
    let mut out = String::new();
    for line in text.trim().lines() {
        let line = line.trim_end();
        if line.is_empty() {
            let _ = writeln!(out, "{indent}///");
        } else {
            let _ = writeln!(out, "{indent}/// {line}");
        }
    }
    out
}

/// The Rust type of a property or field.
fn rust_type(kind: &str, of: &str, list: bool, required: bool) -> String {
    let base = match kind {
        "id" => "types::Uuid".to_owned(),
        "record_ref" => "types::RecordRef".to_owned(),
        "record" => record_type_name(of),
        "enum" => enum_type_name(of),
        "bool" => "bool".to_owned(),
        "int" => "i64".to_owned(),
        "duration_ms" | "bytes" => "u64".to_owned(),
        "timestamp" => "types::DateTime<types::Utc>".to_owned(),
        "date" => "types::NaiveDate".to_owned(),
        _ => "String".to_owned(),
    };
    let base = if list { format!("Vec<{base}>") } else { base };
    if required {
        base
    } else {
        format!("Option<{base}>")
    }
}

fn field(out: &mut String, description: &str, name: &str, kind: &str, required: bool) {
    out.push_str(&doc(description, "    "));
    if !required {
        out.push_str("    #[serde(skip_serializing_if = \"Option::is_none\")]\n");
    }
    let _ = writeln!(out, "    pub {name}: {kind},");
}

fn event_struct(plan: &Plan, event: &EventRow) -> String {
    let mut out = String::new();
    out.push_str(&doc(
        &format!(
            "`{}` v{}: {}\n\nFires when: {}",
            event.name, event.version, event.description, event.fires_when
        ),
        "",
    ));
    out.push_str("#[derive(Debug, Clone, PartialEq, serde::Serialize)]\n");
    let _ = writeln!(out, "pub struct {} {{", event_type_name(event));
    let workspace = event.scope == "workspace";
    if workspace {
        out.push_str(
            "    /// The workspace it happened in (written in the envelope, not the body).\n",
        );
        out.push_str("    #[serde(skip)]\n");
        out.push_str("    pub workspace: types::WorkspaceId,\n");
    }
    for row in plan.properties_of(&event.name, event.version) {
        field(
            &mut out,
            &row.description,
            &row.property,
            &rust_type(&row.kind, &row.of, row.list, row.required),
            row.required,
        );
    }
    out.push('}');
    // A struct with no fields at all is written `pub struct Name {}`.
    out.replace(" {\n}", " {}")
}

fn event_impl(event: &EventRow) -> String {
    let type_name = event_type_name(event);
    let mut out = String::new();
    let _ = writeln!(out, "impl types::TrackedEvent for {type_name} {{");
    out.push_str(&constant(
        "NAME",
        "&'static str",
        &format!("\"{}\"", event.name),
    ));
    let _ = writeln!(out, "    const VERSION: u16 = {};", event.version);
    out.push_str(&constant(
        "MODULE",
        "&'static str",
        &format!("\"{}\"", event.module),
    ));
    let workspace = event.scope == "workspace";
    let _ = writeln!(out, "    const WORKSPACE_SCOPED: bool = {workspace};");
    out.push('\n');
    out.push_str("    fn workspace(&self) -> Option<types::WorkspaceId> {\n");
    if workspace {
        out.push_str("        Some(self.workspace)\n");
    } else {
        out.push_str("        None\n");
    }
    out.push_str("    }\n}");
    out
}

/// `    const NAME: TYPE = VALUE;`, broken after `=` as rustfmt does when it
/// is too long.
fn constant(name: &str, kind: &str, value: &str) -> String {
    let line = format!("    const {name}: {kind} = {value};");
    if line.len() <= MAX_WIDTH {
        format!("{line}\n")
    } else {
        format!("    const {name}: {kind} =\n        {value};\n")
    }
}

fn record_struct(plan: &Plan, record: &str) -> String {
    let mut out = String::new();
    out.push_str(&doc(
        &format!(
            "A snapshot of a `{record}`, filled from the `{}` module's own rows in the \
             transaction of the change.",
            module_of(record)
        ),
        "",
    ));
    out.push_str("#[derive(Debug, Clone, PartialEq, serde::Serialize)]\n");
    let _ = writeln!(out, "pub struct {} {{", record_type_name(record));
    for row in plan.fields_of(record) {
        field(
            &mut out,
            &row.description,
            &row.field,
            &rust_type(&row.kind, &row.enumeration, row.list, row.required),
            row.required,
        );
    }
    out.push('}');
    out.replace(" {\n}", " {}")
}

fn enum_item(plan: &Plan, enumeration: &str) -> String {
    let mut out = String::new();
    out.push_str(&doc(&format!("The values of `{enumeration}`."), ""));
    out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize)]\n");
    let _ = writeln!(out, "pub enum {} {{", enum_type_name(enumeration));
    for row in plan.values_of(enumeration) {
        out.push_str(&doc(&row.description, "    "));
        let _ = writeln!(out, "    #[serde(rename = \"{}\")]", row.value);
        let _ = writeln!(out, "    {},", pascal(&row.value));
    }
    out.push('}');
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{ChangelogRow, EnumRow, PropertyRow, RecordRow};

    fn plan() -> Plan {
        let mut plan = Plan::empty();
        plan.changelog.push(ChangelogRow {
            date: "2026-10-23".into(),
            plan_version: 1,
            change: "First".into(),
            pr: "#1".into(),
        });
        plan.events.push(EventRow {
            name: "things.thing_made".into(),
            version: 1,
            module: "things".into(),
            object: "thing".into(),
            action: "made".into(),
            scope: "workspace".into(),
            status: "live".into(),
            actor_types: vec!["user".into()],
            description: "A thing was made.".into(),
            fires_when: "Someone makes one.".into(),
            added_in: 1,
            openspec_change: "add-things".into(),
        });
        plan.properties.push(PropertyRow {
            event: "things.thing_made".into(),
            version: 1,
            property: "thing".into(),
            kind: "record".into(),
            of: "things.thing".into(),
            required: true,
            classification: "operational".into(),
            description: "The thing.".into(),
            ..PropertyRow::default()
        });
        plan.records.push(RecordRow {
            record: "things.thing".into(),
            field: "colour".into(),
            kind: "enum".into(),
            enumeration: "things.colour".into(),
            required: false,
            classification: "operational".into(),
            description: "Its colour.".into(),
            ..RecordRow::default()
        });
        plan.enums.push(EnumRow {
            enumeration: "things.colour".into(),
            value: "dark_red".into(),
            description: "Dark red.".into(),
        });
        plan
    }

    #[test]
    fn generation_is_deterministic() {
        assert_eq!(files(&plan()), files(&plan()));
        let mut shuffled = plan();
        shuffled.changelog.reverse();
        assert_eq!(files(&shuffled), files(&plan()));
    }

    #[test]
    fn generates_the_kernel_and_each_owning_module() {
        let files = files(&plan());
        let paths: Vec<&str> = files.keys().map(String::as_str).collect();
        assert_eq!(
            paths,
            [
                "crates/kernel/src/tracking/tracking.gen.rs",
                "crates/modules/things/src/tracking.gen.rs",
                MIRROR,
            ]
        );
        let things = &files["crates/modules/things/src/tracking.gen.rs"];
        assert!(things.starts_with(RUST_HEADER));
        assert!(things.ends_with("}\n"));
        assert!(things.contains("pub struct ThingMade {"));
        assert!(things.contains("    pub thing: ThingSnapshot,"));
        assert!(things.contains("    pub colour: Option<Colour>,"));
        assert!(things.contains("    DarkRed,"));
        assert!(things.contains("impl types::TrackedEvent for ThingMade {"));
        let kernel = &files["crates/kernel/src/tracking/tracking.gen.rs"];
        assert!(kernel.contains("pub const PLAN_VERSION: u32 = 1;"));
        assert!(!kernel.contains("use "));
    }

    #[test]
    fn the_mirror_holds_each_events_schema() {
        let mirror: Value = serde_json::from_str(&files(&plan())[MIRROR]).unwrap();
        assert_eq!(mirror["plan_version"], 1);
        let schema = &mirror["events"][0]["schema"];
        assert_eq!(schema["required"], json!(["thing"]));
        assert_eq!(
            schema["properties"]["thing"]["properties"]["colour"]["enum"],
            json!(["dark_red"])
        );
    }

    #[test]
    fn long_constants_break_like_rustfmt() {
        let long = "x".repeat(80);
        assert!(constant("NAME", "&'static str", &format!("\"{long}\"")).contains("=\n        \""));
        assert_eq!(
            constant("NAME", "&'static str", "\"a\""),
            "    const NAME: &'static str = \"a\";\n"
        );
    }
}
