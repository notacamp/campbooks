//! `cargo xtask ispdb`: refresh the provider database the connectors module
//! bundles (Thunderbird's ISPDB, `thundernest/autoconfig`, MPL-2.0) for
//! finding a mailbox's IMAP and SMTP servers without asking a third party.
//!
//! It clones the repository (shallow, with `git`), copies `ispdb/*.xml` and
//! the licence into `crates/modules/connectors/ispdb/`, and writes the index
//! that embeds them (`crates/modules/connectors/src/imap/ispdb_files.rs`).
//! The files are used unmodified; commit them with the index.

use std::{fmt::Write as _, fs, path::Path, process::Command};

use anyhow::{Context as _, Result, bail};

/// Where the database comes from.
const REPOSITORY: &str = "https://github.com/thundernest/autoconfig";

/// Where the files go, from the workspace root.
const TARGET: &str = "crates/modules/connectors/ispdb";

/// The generated index, from the workspace root.
const INDEX: &str = "crates/modules/connectors/src/imap/ispdb_files.rs";

/// Refresh the bundled database.
pub fn run(root: &Path) -> Result<String> {
    let checkout = std::env::temp_dir().join(format!("campbooks-ispdb-{}", std::process::id()));
    if checkout.exists() {
        fs::remove_dir_all(&checkout).context("clearing the previous checkout")?;
    }
    let cloned = Command::new("git")
        .args(["clone", "--quiet", "--depth", "1", REPOSITORY])
        .arg(&checkout)
        .status()
        .context("running git clone")?;
    if !cloned.success() {
        bail!("git clone {REPOSITORY} failed");
    }
    let head = Command::new("git")
        .arg("-C")
        .arg(&checkout)
        .args(["rev-parse", "HEAD"])
        .output()
        .context("running git rev-parse")?;
    let commit = String::from_utf8(head.stdout)
        .context("reading the commit")?
        .trim()
        .to_owned();

    let target = root.join(TARGET);
    if target.exists() {
        fs::remove_dir_all(&target).context("clearing the old database")?;
    }
    fs::create_dir_all(&target)?;
    let mut names = Vec::new();
    for entry in fs::read_dir(checkout.join("ispdb")).context("reading ispdb/")? {
        let path = entry?.path();
        let Some(name) = path
            .file_name()
            .and_then(|n| n.to_str())
            .and_then(|n| n.strip_suffix(".xml"))
        else {
            continue;
        };
        // A provider id is a domain name; anything else is not copied.
        if !name
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'.' || b == b'-')
        {
            continue;
        }
        let text = fs::read_to_string(&path).with_context(|| format!("{name}.xml is not UTF-8"))?;
        fs::write(target.join(format!("{name}.xml")), text)?;
        names.push(name.to_owned());
    }
    fs::copy(checkout.join("LICENSE"), target.join("LICENSE")).context("copying the licence")?;
    names.sort();
    fs::write(root.join(INDEX), index(&commit, &names))?;
    let formatted = Command::new("rustfmt")
        .args(["--edition", "2024"])
        .arg(root.join(INDEX))
        .status()
        .context("running rustfmt")?;
    if !formatted.success() {
        bail!("rustfmt {INDEX} failed");
    }
    fs::remove_dir_all(&checkout).ok();
    Ok(format!(
        "{} provider files from {REPOSITORY} at {commit} in {TARGET}; review and commit them with \
         {INDEX}",
        names.len()
    ))
}

/// The Rust index that embeds `names` (sorted), taken at `commit`.
fn index(commit: &str, names: &[String]) -> String {
    let mut out = format!(
        "//! Generated by `cargo xtask ispdb` from thundernest/autoconfig at\n\
         //! `{commit}` (MPL-2.0, see `ispdb/LICENSE`). Do not edit.\n\n\
         /// The bundled provider database: each file's name (its provider id) and\n\
         /// XML.\n\
         pub static FILES: &[(&str, &str)] = &[\n"
    );
    for name in names {
        let _ = writeln!(
            out,
            "    (\"{name}\", include_str!(\"../../ispdb/{name}.xml\")),"
        );
    }
    out.push_str("];\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_index_embeds_every_file() {
        let index = index("abc", &["aol.com".to_owned(), "yahoo.com".to_owned()]);
        assert!(index.contains("`abc`"));
        assert!(index.contains(r#"("aol.com", include_str!("../../ispdb/aol.com.xml")),"#));
        assert!(index.contains(r#"("yahoo.com", include_str!("../../ispdb/yahoo.com.xml")),"#));
    }
}
