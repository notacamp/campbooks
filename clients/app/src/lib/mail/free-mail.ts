/**
 * Whether `domain` belongs to a free mail provider: the domain itself, or one
 * under it (`mail.yahoo.fr` is Yahoo's), as the server compares registrable
 * domains.
 */
export function isFreeMailDomain(domain: string): boolean {
  const name = domain.trim().toLowerCase().replace(/\.+$/u, "");
  for (let at = name; at.includes("."); at = at.slice(at.indexOf(".") + 1)) {
    if (FREE_MAIL.has(at)) {
      return true;
    }
  }
  return false;
}
